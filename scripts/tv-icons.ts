// Writes the TV apps' icons from Phosphor (@phosphor-icons/core), the set the web app uses:
// apps/vega/src/icon-paths.ts and the Fire TV app's NvIcons. To add an icon, add it below and run
//
//   bun scripts/tv-icons.ts
//
// TVs use the bold weight, legible from the sofa; solid controls use fill.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

type Weight = "bold" | "fill";

const ICONS: Record<string, [glyph: string, weight: Weight]> = {
  home: ["house", "bold"],
  search: ["magnifying-glass", "bold"],
  film: ["film-slate", "bold"],
  tv: ["television", "bold"],
  settings: ["gear-six", "bold"],
  play: ["play", "fill"],
  pause: ["pause", "fill"],
  skipNext: ["skip-forward", "fill"],
  rewind: ["rewind", "fill"],
  forward: ["fast-forward", "fill"],
  restart: ["arrow-counter-clockwise", "bold"],
  check: ["check", "bold"],
  subtitles: ["closed-captioning", "bold"],
  audio: ["speaker-high", "bold"],
  layers: ["stack", "bold"],
  server: ["hard-drives", "bold"],
  signOut: ["sign-out", "bold"],
  users: ["users", "bold"],
  back: ["arrow-left", "bold"],
  arrowRight: ["arrow-right", "bold"],
};

const root = join(import.meta.dirname, "..");
const assets = join(root, "node_modules/@phosphor-icons/core/assets");

function paths(glyph: string, weight: Weight): string[] {
  const svg = readFileSync(join(assets, weight, `${glyph}-${weight}.svg`), "utf8");
  const shapes = svg.match(/<(?!svg|\/)[a-z]+/g) ?? [];
  if (shapes.some((s) => s !== "<path")) throw new Error(`${glyph}-${weight}: only <path> is supported, found ${shapes.join(" ")}`);
  return [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]!);
}

const entries = Object.entries(ICONS).map(([name, [glyph, weight]]) => ({ name, glyph, weight, d: paths(glyph, weight) }));
const header = "Generated by scripts/tv-icons.ts from Phosphor (phosphoricons.com), the web app's icon set. Edit the list there.";

writeFileSync(
  join(root, "apps/vega/src/icon-paths.ts"),
  `// ${header}
// Each icon is filled paths on a 256-unit grid.
export const ICON_PATHS = {
${entries.map((e) => `  ${e.name}: [${e.d.map((d) => `'${d}'`).join(", ")}], // ${e.glyph}, ${e.weight}`).join("\n")}
} as const;

export type IconName = keyof typeof ICON_PATHS;
`,
);

const pascal = (s: string) => s[0]!.toUpperCase() + s.slice(1);
writeFileSync(
  join(root, "apps/firetv/app/src/main/java/app/nuvora/tv/ui/common/Icons.kt"),
  `package app.nuvora.tv.ui.common

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.PathParser
import androidx.compose.ui.unit.dp

/** ${header} Filled paths on a 256-unit grid, white for tinting. */
object NvIcons {
${entries.map((e) => `    /** ${e.glyph}, ${e.weight} */\n    val ${pascal(e.name)} = icon(${e.d.map((d) => `"${d}"`).join(", ")})`).join("\n")}

    private fun icon(vararg paths: String): ImageVector {
        val builder = ImageVector.Builder(defaultWidth = 24.dp, defaultHeight = 24.dp, viewportWidth = 256f, viewportHeight = 256f)
        for (d in paths) builder.addPath(PathParser().parsePathString(d).toNodes(), fill = SolidColor(Color.White))
        return builder.build()
    }
}
`,
);

console.log(`Wrote ${entries.length} icons for Vega and Fire TV.`);

private val byCode: Map<String, Language> = buildMap {
    for (l in LANGUAGES) {
        put(l.iso1, l)
        put(l.code, l)
        l.alt?.let { put(it, l) }
    }
}

/** Any form of a language code (`"de"`, `"ger"`, `"deu"`, `"de-AT"`), as the server's three letters; null for none or unknown. */
fun languageCode(code: String?): String? {
    val c = code?.trim()?.lowercase()?.substringBefore('-')?.substringBefore('_') ?: return null
    return byCode[c]?.code
}

/** `"spa"` -> `"Spanish"`; the code itself when unknown, "Unknown" for none. */
fun languageName(code: String?): String {
    if (code.isNullOrBlank() || code == "und") return "Unknown language"
    return byCode[code.trim().lowercase().substringBefore('-')]?.name ?: code
}
